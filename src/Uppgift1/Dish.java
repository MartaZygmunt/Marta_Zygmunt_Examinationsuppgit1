package Uppgift1;

public class Dish {
    public String name;
    public double price;
    public String type;
    public int calories;

    public Dish (String namn, double pris, String typ, int kalorier) {
        this.name = namn;
        this.price = pris;
        this.type = typ;
        this.calories = kalorier;
    }

}